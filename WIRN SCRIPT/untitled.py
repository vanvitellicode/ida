eta = 1.0  # resistance effect

# === FUNZIONE DI CALCOLO RISCHIO ===
def compute_risk(B, D, N):
    N_total = B + D + N
    if N_total == 0:
        return 0.0
    Pi = B / N_total
    Si = N / N_total
    Ui = D / N_total
    Ri = Pi * Si * rho * (1 - eta * Ui)
    return round(Ri, 5)

