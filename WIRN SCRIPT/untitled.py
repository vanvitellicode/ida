#!/usr/bin/env python3
# kpi_by_post.py
import pandas as pd
import numpy as np
from pathlib import Path

# ---------------------------------------------------------------------------
# 1) Elenco dei file da analizzare (stessa cartella dello script)
# ---------------------------------------------------------------------------
FILES = [
    "combined_dataset.csv",
    "putinmissing-all-rnr-threads_rumours.csv",
    "charliehebdo-all-rnr-threads_rumours.csv"
]

# ---------------------------------------------------------------------------
# 2) Sinonimi per auto-detect colonne
# ---------------------------------------------------------------------------
CANDIDATES = {
    "post_id": [
        "tweet_id", "id", "post_id", "conversation_id",
        "thread_id", "postid"
    ],
    "user_id": [
        "user_id", "userid", "author_id", "user",
        "UserId"
    ],
    "timestamp": [
        "created_at", "commentat", "datetime",
        "timestamp", "date", "time"
    ],
    "reactions": [
        "favorite_count", "likes", "reactionscount",
        "like_count", "share_count", "shares",
        "ReactionsCount"
    ],
    "replies": [
        "reply_count", "replies", "comment_count",
        "SubCommentsCount"
    ],
}

def find_col(cols, options):
    """Restituisce il primo nome presente in cols tra le opzioni."""
    cols_lc = {c.lower(): c for c in cols}
    for opt in options:
        if opt.lower() in cols_lc:
            return cols_lc[opt.lower()]
    return None

# ---------------------------------------------------------------------------
# 3) KPI per un singolo groupby(post_id)
# ---------------------------------------------------------------------------
def kpis_for_group(df: pd.DataFrame) -> dict:
    df["timestamp"] = pd.to_datetime(df["timestamp"], errors="coerce")

    for c in ("reactions", "replies"):
        df[c] = pd.to_numeric(df[c], errors="coerce").fillna(0)

    df["views"] = df["reactions"] + df["replies"]

    df_sorted  = df.sort_values("timestamp")
    start_time = df_sorted["timestamp"].min()
    end_time   = df_sorted["timestamp"].max()

    unique_reach = df["user_id"].nunique()
    total_views  = df["views"].sum()

    # Time to initial spread (primo record con ≥10 visualizzazioni)
    spread_row = df_sorted[df_sorted["views"] >= 10].head(1)
    t_init = (
        (spread_row["timestamp"].iloc[0] - start_time).total_seconds() / 60
        if not spread_row.empty and pd.notna(start_time) else np.nan
    )

    lifespan = (
        (end_time - start_time).total_seconds() / 60
        if pd.notna(end_time) and pd.notna(start_time) else np.nan
    )
    grow_rate = (
        total_views / lifespan if lifespan and lifespan > 0 else np.nan
    )

    return dict(
        unique_reach              = unique_reach,
        views                     = total_views,
        time_to_initial_spread_min= t_init,
        content_lifespan_min      = lifespan,
        grow_rate_tweets_per_min  = grow_rate
    )

# ---------------------------------------------------------------------------
# 4) Elaborazione di tutti i file
# ---------------------------------------------------------------------------
all_kpi_rows = []

for file_name in FILES:
    path = Path(file_name)
    if not path.exists():
        print(f"⚠️  File non trovato: {file_name}")
        continue

    raw = pd.read_csv(path)
    mapping = {}

    # auto-detect
    for logical, opts in CANDIDATES.items():
        col = find_col(raw.columns, opts)
        if col:
            mapping[logical] = col

    mandatory = ("post_id", "user_id", "timestamp")
    if not all(m in mapping for m in mandatory):
        print(f"❌  Colonne fondamentali mancanti in {file_name}. Saltato.")
        continue

    # reactions / replies obbligatorie (zero se assenti)
    if "reactions" not in mapping:
        raw["reactions"] = 0
        mapping["reactions"] = "reactions"
    if "replies" not in mapping:
        raw["replies"] = 0
        mapping["replies"] = "replies"

    # dataframe uniformato
    df = raw.rename(columns={
        mapping["post_id"]  : "post_id",
        mapping["user_id"]  : "user_id",
        mapping["timestamp"]: "timestamp",
        mapping["reactions"]: "reactions",
        mapping["replies"]  : "replies"
    })[["post_id", "user_id", "timestamp", "reactions", "replies"]].copy()

    # salva versione pulita
    clean_name = f"clean_{path.stem}.csv"
    df.to_csv(clean_name, index=False)
    print(f"✅ Salvato {clean_name}")

    # KPI per ogni post_id
    for post_id, grp in df.groupby("post_id"):
        kpi_vals = kpis_for_group(grp)
        kpi_vals.update(dataset=path.stem, post_id=post_id)
        all_kpi_rows.append(kpi_vals)

# ---------------------------------------------------------------------------
# 5) Output finale
# ---------------------------------------------------------------------------
out_df = pd.DataFrame(all_kpi_rows)[[
    "dataset",
    "post_id",
    "unique_reach",
    "views",
    "time_to_initial_spread_min",
    "content_lifespan_min",
    "grow_rate_tweets_per_min"
]]

out_df.to_csv("kpi_by_post.csv", index=False)
print("✅ KPI per post salvati in kpi_by_post.csv")

#!/usr/bin/env python3
"""
Publication-ready KPI comparison
================================
This script loads raw KPI data for different online discussions, removes outliers,
computes the mean KPI value **per dataset**, and produces publication-quality
violin plots to compare the full distributions of each KPI side-by-side.

Input files (CSV) must be present in the same directory as the script:
    • kpi_putinmissing.csv
    • kpi_charliehebdo.csv

The script saves one PNG file per KPI (300 dpi) and a CSV file containing the mean
values after outlier removal.

Usage
-----
$ python kpi_publication_analysis.py

Dependencies
------------
Python ≥3.9 and the libraries pandas, seaborn and matplotlib.
Install with:
    pip install pandas seaborn matplotlib
"""
from __future__ import annotations

from pathlib import Path
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# ----------------------------------------------------------------------------
# Configuration — edit here if you add datasets or KPI columns
# ----------------------------------------------------------------------------
DATASET_FILES: dict[str, str] = {
    "Putin Missing": "kpi_putinmissing.csv",
    "Charlie Hebdo": "kpi_charliehebdo.csv",
}
# KPI columns to analyse (must exist in every CSV)
KPI_COLUMNS: list[str] = [
    "unique_reach",
    "views",
    "time_to_initial_spread_min",
    "content_lifespan_min",
    "grow_rate_tweets_per_min",
]
OUTPUT_DIR = Path("figures")  # where to save PNGs and the summary CSV
OUTPUT_DIR.mkdir(exist_ok=True)

# ----------------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------------

def remove_outliers_iqr(df: pd.DataFrame, column: str) -> pd.DataFrame:
    """Return *df* with values outside 1.5·IQR for *column* filtered out."""
    q1 = df[column].quantile(0.25)
    q3 = df[column].quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    return df[(df[column] >= lower) & (df[column] <= upper)]


# ----------------------------------------------------------------------------
# Load and concatenate datasets, keeping a label column
# ----------------------------------------------------------------------------
frames: list[pd.DataFrame] = []
for label, filename in DATASET_FILES.items():
    df = pd.read_csv(filename)
    df["dataset"] = label
    frames.append(df)
raw_data = pd.concat(frames, ignore_index=True)

# ----------------------------------------------------------------------------
# Clean data: remove outliers in each KPI *within each dataset*.
# ----------------------------------------------------------------------------
filtered_frames: list[pd.DataFrame] = []
for label, group in raw_data.groupby("dataset"):
    cleaned = group.copy()
    for col in KPI_COLUMNS:
        cleaned = remove_outliers_iqr(cleaned, col)
    filtered_frames.append(cleaned)
clean_data = pd.concat(filtered_frames, ignore_index=True)

# ----------------------------------------------------------------------------
# Compute mean KPI values after cleaning and export as CSV.
# ----------------------------------------------------------------------------
mean_table = (
    clean_data.groupby("dataset")[KPI_COLUMNS]
    .mean()
    .round(3)
    .T  # easier to read with KPIs as rows
)
mean_table.to_csv(OUTPUT_DIR / "mean_metrics_by_dataset.csv")

# ----------------------------------------------------------------------------
# Plot distribution comparison for each KPI.
# ----------------------------------------------------------------------------
sns.set_theme(style="whitegrid", context="talk", font_scale=1.1)
for col in KPI_COLUMNS:
    plt.figure(figsize=(6, 4))
    # Violin for the global shape + swarm for the underlying points
    sns.violinplot(x="dataset", y=col, data=clean_data, inner="quartile", cut=0)
    sns.swarmplot(x="dataset", y=col, data=clean_data, color="k", size=3, alpha=0.4)
    plt.title(col.replace("_", " ").title())
    plt.xlabel("")
    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / f"distribution_{col}.png", dpi=300)
    plt.close()

print("📈 Finished. Figures and summary CSV saved to", OUTPUT_DIR.resolve())

