"""
KPI Comparison – variante “raw vs mean”
======================================
Confronta i tre dataset KPI (Putin Missing, Charlie Hebdo, Deepfake) e, quando
esistono colonne aggregate con suffisso `_mean`, le include **come KPI a parte**
così che, ad esempio, il grafico di `content_lifespan_min_mean` appaia subito
a fianco di quello di `content_lifespan_min`.

Flusso di lavoro:
1. **Caricamento** dei tre CSV.
2. **Normalizzazione nomi** (minuscolo, rimozione spazi) ma **non** si elimina
   il suffisso `_mean`; le varianti `grow_rate_views_per_min` e
   `grow_rate_tweets_per_min` confluiscono in `grow_rate_per_min` (e la variante
   `_mean` corrispondente).
3. KPI selezionati se presenti in **almeno un dataset** (abbiamo tolto il vincolo
   “≥2 dataset” per consentire le metriche che esistono solo come media).
4. **Rimozione outlier** (1,5·IQR) *per ogni (dataset, KPI)* disponibile.
5. **Tabella medie** (`mean_metrics_by_dataset.csv`) completa di tutte le metriche.
6. **Grafici violin+swarm** per ogni KPI; se una metrica esiste in un solo
   dataset, il grafico mostra comunque quell’unica distribuzione (utile per le
   colonne `_mean`). Su ogni plot sono sovrapposte le medie (rombo rosso).

Uso rapido
-----------
```bash
pip install pandas seaborn matplotlib
python kpi_publication_analysis.py
```

Gli output sono salvati nella cartella `figures/`.
"""
from __future__ import annotations

from pathlib import Path
import re
from collections import Counter
from typing import Dict, Set

import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# ---------------------------------------------------------------------------
# Config – file sorgente
# ---------------------------------------------------------------------------
DATASET_FILES: Dict[str, str] = {
    "Putin Missing": "kpi_putinmissing.csv",
    "Charlie Hebdo": "kpi_charliehebdo.csv",
    "Deepfake": "kpi_deepfake.csv",
}
OUTPUT_DIR = Path("figures")
OUTPUT_DIR.mkdir(exist_ok=True)

# ---------------------------------------------------------------------------
# Helper – normalizza ma conserva _mean
# ---------------------------------------------------------------------------
_grow_rate_full_re = re.compile(r"grow_rate_(views|tweets)_per_min(_mean)?$", re.IGNORECASE)


def canonical(col: str) -> str:
    col = col.strip().lower().replace(" ", "")
    # uniforma grow_rate_* to grow_rate_per_min (aggiungendo _mean se presente)
    m = _grow_rate_full_re.match(col)
    if m:
        return "grow_rate_per_min" + ("_mean" if m.group(2) else "")
    return col  # lascia tutto il resto intatto (incl. _mean)


# ---------------------------------------------------------------------------
# Carica dataset e normalizza
# ---------------------------------------------------------------------------
frames = []
cols_by_dataset: Dict[str, Set[str]] = {}

for label, csv_path in DATASET_FILES.items():
    df = pd.read_csv(csv_path)
    numeric = df.select_dtypes("number").columns
    rename_map = {c: canonical(c) for c in numeric}
    df = df.rename(columns=rename_map)
    df["dataset"] = label
    frames.append(df)
    cols_by_dataset[label] = set(rename_map.values())

# ---------------------------------------------------------------------------
# Elenco KPI (anche se presenti in un solo dataset)
# ---------------------------------------------------------------------------
KPI_COLUMNS = sorted(set().union(*cols_by_dataset.values()))
print("➡️ KPI totali (raw + mean):", ", ".join(KPI_COLUMNS))

raw_data = pd.concat(frames, ignore_index=True)

# ---------------------------------------------------------------------------
# Outlier cleaning
# ---------------------------------------------------------------------------

def keep_mask(series: pd.Series) -> pd.Series:
    if series.dropna().empty:
        return pd.Series([True] * len(series))
    q1, q3 = series.quantile([0.25, 0.75])
    iqr = q3 - q1
    lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr
    return (series >= lower) & (series <= upper)


clean_frames = []
for label, grp in raw_data.groupby("dataset"):
    cleaned = grp.copy()
    for col in KPI_COLUMNS:
        if col in cleaned:
            mask = keep_mask(cleaned[col])
            cleaned = cleaned[mask | cleaned[col].isna()]
    clean_frames.append(cleaned)
clean_data = pd.concat(clean_frames, ignore_index=True)

# ---------------------------------------------------------------------------
# Tabella medie (wide)
# ---------------------------------------------------------------------------
mean_table = (
    clean_data.melt(id_vars=["dataset"], value_vars=KPI_COLUMNS, var_name="kpi", value_name="value")
    .dropna(subset=["value"])
    .groupby(["kpi", "dataset"])["value"].mean()
    .unstack("dataset")
    .round(3)
    .sort_index()
)
mean_table.to_csv(OUTPUT_DIR / "mean_metrics_by_dataset.csv")

# ---------------------------------------------------------------------------
# Grafici
# ---------------------------------------------------------------------------
print("📊 Creazione violin plot …")
sns.set_theme(style="whitegrid", context="talk", font_scale=1.1)
for col in KPI_COLUMNS:
    subset = clean_data[["dataset", col]].dropna()
    plt.figure(figsize=(7, 4.8))
    sns.violinplot(x="dataset", y=col, data=subset, inner="quartile", cut=0)
    sns.swarmplot(x="dataset", y=col, data=subset, color="k", size=3, alpha=0.4)

    # Overlay della media
    means = subset.groupby("dataset")[col].mean()
    sns.pointplot(x=means.index, y=means.values, join=False, markers="d", scale=1.4, color="firebrick")

    plt.title(col.replace("_", " ").title())
    plt.xlabel("")
    plt.tight_layout()
    out_file = OUTPUT_DIR / f"distribution_{col}.png"
    plt.savefig(out_file, dpi=300)
    plt.close()
    print("  ✔", out_file.name)

print("✅ Tutto pronto! Grafici e tabella in", OUTPUT_DIR.resolve())

