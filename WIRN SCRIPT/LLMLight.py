def load_annotated_threads(event_dir, category, limit):
    data = []
    path = os.path.join(event_dir, category)
    threads = [d for d in os.listdir(path) if os.path.isdir(os.path.join(path, d))][:limit]
    for thread_id in tqdm(threads, desc=f"Processing {category}"):
        thread_path = os.path.join(path, thread_id)
        source_path = os.path.join(thread_path, "source-tweet", "source-tweet.json")
        reaction_path = os.path.join(thread_path, "reactions")
        annotation_path = os.path.join(thread_path, "annotation.json")

        if not os.path.exists(annotation_path):
            continue

        try:
            with open(source_path, "r", encoding="utf-8") as f:
                context = json.load(f)["text"]
            with open(annotation_path, "r", encoding="utf-8") as f:
                annotations = json.load(f)
        except Exception:
            continue

        for tweet_id, stance in annotations.items():
            reply_file = os.path.join(reaction_path, f"{tweet_id}.json")
            if not os.path.exists(reply_file):
                continue
            try:
                with open(reply_file, "r", encoding="utf-8") as f:
                    reply_text = json.load(f)["text"]
                data.append({
                    "tweet_id": tweet_id,
                    "context": context,
                    "reply": reply_text,
                    "label": stance
                })
            except Exception:
                continue
    return pd.DataFrame(data)

