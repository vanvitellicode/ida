import json
from bson import BSON       # classe ufficiale in pymongo
from bson.json_util import loads  # per Extended JSON, opzionale

def json_to_bson(input_json_path: str, output_bson_path: str) -> None:
    # Carica JSON (Extended JSON se serve)
    with open(input_json_path, 'r', encoding='utf-8') as f:
        raw = f.read()
    try:
        doc = loads(raw)  # supporta Extended JSON
    except Exception:
        doc = json.loads(raw)  # JSON puro

    # Serializza in BSON
    bson_data: bytes = BSON.encode(doc)

    # Salva su file binario
    with open(output_bson_path, 'wb') as f:
        f.write(bson_data)

